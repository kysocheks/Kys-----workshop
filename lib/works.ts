/**
 * KySочек Workshop — единственный источник правды.
 *
 * Все проекты трёх разделов, их палитры, кадры и ссылки. Больше нигде в коде
 * нет ни одного цвета проекта и ни одного адреса.
 *
 * Палитра описывается пятью цветами и только в HEX. Линии и заливки не хранятся
 * отдельно — они выводятся из чернил и акцента прямо в CSS. Так цвет нигде не
 * задан дважды, и смешивать палитры можно арифметикой по каналам.
 */

export type Palette = {
  readonly base: string;
  readonly surface: string;
  readonly ink: string;
  readonly inkDim: string;
  readonly accent: string;
  readonly scheme: 'dark' | 'light';
};

/**
 * Палитра самого зала.
 *
 * Тёмный графит и сурик — цвет, которым чертёжник правит по готовому. Ни один
 * экспонат такого акцента не использует, поэтому зал узнаётся всегда, в какую
 * бы сторону ни качнулся свет.
 */
