export type Shot = {
  readonly src: string;
  readonly alt: string;
  readonly width: number;
  readonly height: number;
};

export type Project = {
  readonly slug: string;
  readonly category: Category;
  readonly title: string;
  /** Одна строка: что это такое. */
  readonly tagline: string;
  readonly year: string;
  /** Абзац: замысел. */
  readonly premise: string;
  /** Две-три строки: что в работе живого. Без перечисления технологий. */
  readonly notes: readonly string[];
  /** Боевой адрес. null — ещё не опубликовано. */
  readonly href: string | null;
  /** Ярлык у названия: статус или природа работы. Показывается всегда. */
  readonly badge?: string;
  /**
   * Честная приписка о положении дел. Нужна там, где иначе получилось бы
   * враньё: невышедшая игра не должна выглядеть вышедшей, а рекламный шаблон
   * несуществующего заведения — настоящим заведением.
   */
  readonly status?: string;
  readonly shot: Shot | null;
  /**
   * Дополнительные полотна. Если они есть, работа получает не карточку, а
   * показ: кадры идут один за другим во весь экран.
   */
  readonly gallery?: readonly (Shot & { readonly caption: string })[];
  readonly palette: Palette;
};

