/* --------------------------------------------------- смешивание палитр --- */

function channels(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  const full =
    h.length === 3
      ? h
          .split('')
          .map((c) => c + c)
          .join('')
      : h;
  const n = Number.parseInt(full, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function toHex(r: number, g: number, b: number): string {
  const clamp = (v: number) => Math.max(0, Math.min(255, Math.round(v)));
  return `#${((1 << 24) | (clamp(r) << 16) | (clamp(g) << 8) | clamp(b)).toString(16).slice(1)}`;
}

/** Смешать два цвета: t = 0 — целиком первый, t = 1 — целиком второй. */
export function mix(from: string, to: string, t: number): string {
  const [r1, g1, b1] = channels(from);
  const [r2, g2, b2] = channels(to);
  return toHex(r1 + (r2 - r1) * t, g1 + (g2 - g1) * t, b1 + (b2 - b1) * t);
}

function luminance(hex: string): number {
  const [r, g, b] = channels(hex).map((v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  }) as [number, number, number];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** Коэффициент контраста по WCAG. 4.5 — порог для обычного текста. */
export function contrast(a: string, b: string): number {
  const l1 = luminance(a);
  const l2 = luminance(b);
  const [hi, lo] = l1 > l2 ? [l1, l2] : [l2, l1];
  return (hi + 0.05) / (lo + 0.05);
}

/**
 * Осветлить цвет ровно настолько, чтобы он читался на своём фоне.
 *
 * Ограничивать такие цвета по размеру шрифта бессмысленно — проще поднять сам
 * цвет до порога. Оттенок сохраняется: подмешивается белый, а не серый.
 */
export function readable(color: string, bg: string, target = 4.5): string {
  if (contrast(color, bg) >= target) return color;
  const towards = luminance(bg) > 0.5 ? '#000000' : '#FFFFFF';
  for (let t = 0.05; t <= 1; t += 0.05) {
    const candidate = mix(color, towards, t);
    if (contrast(candidate, bg) >= target) return candidate;
  }
  return towards;
}

/** Палитра зала, залитого светом выбранного экспоната. */
export function tinted(project: Project | null): Palette {
  if (!project) return SHELL;
  const p = project.palette;

  // Светлые работы тянут зал вполсилы: на полной тяге графит уезжает в
  // мутно-серое и проваливает контраст.
  const pull = p.scheme === 'light' ? 0.5 : 1;

  const base = mix(
    mix(SHELL.base, p.base, TINT.base * pull),
    p.accent,
    TINT.accentInBase * pull,
  );
  const surface = mix(
    mix(SHELL.surface, p.surface, TINT.surface * pull),
    p.accent,
    TINT.accentInSurface * pull,
  );

  // Худший случай для любого цвета — самая светлая поверхность, на которую он
  // когда-либо ложится. Для тёмного зала это `surface`, а не `base`.
  const worst = (color: string, target: number) =>
    readable(readable(color, base, target), surface, target);

  return {
    base,
    surface,
    ink: worst(mix(SHELL.ink, p.ink, TINT.ink), 7),
    inkDim: worst(mix(SHELL.inkDim, p.inkDim, TINT.inkDim), 4.5),
    accent: worst(p.accent, 4.5),
    scheme: SHELL.scheme,
  };
}

/** Палитра в виде переменных стилей. */
export function paletteVars(p: Palette): Record<string, string> {
  return {
    '--base': p.base,
    '--surface': p.surface,
    '--ink': p.ink,
    '--ink-dim': p.inkDim,
    '--accent': p.accent,
  };
}
